const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { PGlite } = require('@electric-sql/pglite');
test('events and images enforce teacher-only writes including role revocation and stale versions', async () => {
  const db = new PGlite();
  const teacher = '11111111-1111-4111-8111-111111111111', stranger = '22222222-2222-4222-8222-222222222222';
  try {
    await db.exec(`create role anon; create role authenticated;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema public, auth to anon, authenticated; grant execute on function auth.uid() to anon, authenticated;
      insert into auth.users values ('${teacher}'), ('${stranger}');
      create schema storage;
      create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
      create table storage.objects(id uuid primary key default gen_random_uuid(), bucket_id text references storage.buckets, name text, unique(bucket_id,name));
      alter table storage.objects enable row level security; grant usage on schema storage to anon, authenticated;
      grant select, insert, update, delete on storage.objects to anon, authenticated;`);
    for (const file of ['202609160001_teacher_homework.sql', '202609190001_homework_photos.sql', '202610110001_class_events.sql']) await db.exec(fs.readFileSync(path.join(__dirname, '../supabase/migrations', file), 'utf8'));
    await db.query('insert into school_private.teacher(user_id) values ($1)', [teacher]);
    const insert = "insert into events(kind,title,body,event_date) values ('event','Тесла-шоу','Эксперименты','2026-10-09') returning *";
    const upload = "insert into storage.objects(bucket_id,name) values ('event-photos',$1) returning *";
    const photo = teacher + '.jpg';
    await db.exec('set role anon');
    await assert.rejects(db.query(insert)); await assert.rejects(db.query(upload, [photo]));
    await db.exec('reset role; set role authenticated');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [stranger]);
    await assert.rejects(db.query(insert)); await assert.rejects(db.query(upload, [photo]));
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [teacher]);
    const row = (await db.query(insert)).rows[0];
    await assert.rejects(db.query("insert into events(kind,title,body) values ('test','Контрольная','Тема')"));
    await assert.rejects(db.query("insert into events(kind,title,body,event_date) values ('event','Шоу','Описание','2026-02-30')"));
    await assert.rejects(db.query("update events set title=' '"));
    await assert.rejects(db.query("update events set version=100"));
    await assert.rejects(db.query('update events set photo_paths=$1', [[photo, photo]]));
    await assert.rejects(db.query('update events set photo_paths=$1', [['bad.svg']]));
    await db.query(upload, [photo]); await db.query('update events set photo_paths=$1 where id=$2', [[photo], row.id]);
    assert.equal((await db.query('delete from storage.objects returning *')).rows.length, 0);
    assert.equal((await db.query("update storage.objects set name='other.jpg' returning *")).rows.length, 0);
    assert.equal((await db.query('update events set archived=true where id=$1 and version=1 returning *', [row.id])).rows.length, 0);
    const update = (await db.query('update events set cancelled=true,archived=true where id=$1 and version=2 returning *', [row.id])).rows[0];
    assert.equal(update.version, 3); assert.equal(update.cancelled, true);
    assert.equal((await db.query('delete from events where id=$1 and version=1 returning *', [row.id])).rows.length, 0);
    await db.exec('reset role; set role anon');
    assert.equal((await db.query('select * from events')).rows.length, 1);
    await assert.rejects(db.query("update events set body='Hack'")); await assert.rejects(db.query('delete from events'));
    await db.exec('reset role; set role authenticated');
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [stranger]);
    assert.equal((await db.query("update events set body='Hack' returning *")).rows.length, 0);
    assert.equal((await db.query('delete from events returning *')).rows.length, 0);
    assert.equal((await db.query('delete from storage.objects returning *')).rows.length, 0);
    await db.exec('reset role'); await db.query('update school_private.teacher set user_id=$1', [stranger]);
    await db.exec('set role authenticated'); await db.query("select set_config('request.jwt.claim.sub',$1,false)", [teacher]);
    await assert.rejects(db.query(insert)); await assert.rejects(db.query(upload, [stranger + '.jpg']));
    assert.equal((await db.query('delete from events returning *')).rows.length, 0);
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [stranger]);
    assert.equal((await db.query('delete from events returning *')).rows.length, 1);
    assert.equal((await db.query('delete from storage.objects returning *')).rows.length, 1);
    const announcement = (await db.query("insert into events(kind,title,body) values ('announcement','Новость','Описание') returning *")).rows[0];
    assert.equal(announcement.event_date, null);
  } finally { await db.close(); }
});
